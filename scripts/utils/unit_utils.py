def kg_to_quintal(value):
    """Convert kilograms to quintals."""
    return value / 100


def tonne_to_quintal(value):
    """Convert tonnes to quintals."""
    return value * 10


def mile_to_km(value):
    """Convert miles to kilometres."""
    return value * 1.60934


def inch_to_mm(value):
    """Convert inches to millimetres."""
    return value * 25.4


def fahrenheit_to_celsius(value):
    """Convert Fahrenheit to Celsius."""
    return (value - 32) * 5 / 9